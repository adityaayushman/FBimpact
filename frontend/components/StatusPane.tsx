"use client";

import { useEffect, useState } from "react";
import { API_URL, api, checkpointGeneration, type Health, type ModelCard } from "@/lib/api";
import { SUBPAGES } from "@/lib/route";
import ApiPane from "./ApiPane";
import { PageHeader, Section, TabPanel, Tabs } from "./ui";

interface Props { sub: string; health: Health | null; bootError: string | null }

/** Deployment status: reachability, round-trip latency, the loaded checkpoint, its model card and the API surface. */
export default function StatusPane({ sub, health, bootError }: Props) {
  const [pings, setPings] = useState<number[]>([]);
  const [busy, setBusy] = useState(false);
  const [err, setErr] = useState<string | null>(null);
  const [card, setCard] = useState<ModelCard | null>(null);

  const ping = async () => {
    setBusy(true); setErr(null);
    const t0 = performance.now();
    try {
      const res = await fetch(`${API_URL}/health`, { cache: "no-store" });
      if (!res.ok) throw new Error(`HTTP ${res.status}`);
      setPings((p) => [...p.slice(-9), Math.round(performance.now() - t0)]);
    } catch (e) {
      setErr(e instanceof Error ? e.message : String(e));
    } finally {
      setBusy(false);
    }
  };

  useEffect(() => {
    if (!health) return;
    // Older backends have no /model-card; the 404 is expected, not an error to show.
    api.modelCard().then(setCard).catch(() => setCard(null));
  }, [health]);

  const m = health?.model;
  const gen = m ? checkpointGeneration(m) : null;
  const avg = pings.length ? Math.round(pings.reduce((a, b) => a + b, 0) / pings.length) : null;
  const state = health ? "Reachable" : bootError ? "Unreachable" : "Waking up";
  const stateColour = health ? "var(--calm)" : bootError ? "var(--impact)" : "var(--watch)";

  return (
    <>
      <PageHeader
        eyebrow="Reference"
        title="System status"
        lede="Whether the inference API is up, how quickly it answers, and exactly which checkpoint it is serving."
        actions={<button className="btn" onClick={ping} disabled={busy}>{busy ? "Pinging…" : "Ping the API"}</button>}
      />
      <Tabs view="status" tabs={SUBPAGES.status} value={sub} label="Status sections" />

      <TabPanel view="status" id="health" value={sub}>
        <div className="cols-3">
          <div className="card">
            <div className="card-title">Inference API</div>
            <div className="big" style={{ color: stateColour }}>{state}</div>
            <p className="card-sub mono">{API_URL}</p>
            {bootError && <p className="card-sub">{bootError}</p>}
          </div>
          <div className="card">
            <div className="card-title">Latency</div>
            <div className="big">{pings.length ? `${pings[pings.length - 1]} ms` : "—"}</div>
            <p className="card-sub">
              {avg != null ? `Mean of the last ${pings.length}: ${avg} ms.` : "Press “Ping the API” to measure a round trip."}
            </p>
            {err && <p className="card-sub" style={{ color: "var(--impact)" }}>{err}</p>}
          </div>
          <div className="card">
            <div className="card-title">Deployed checkpoint</div>
            {m ? (
              <ul className="kv">
                <li><span>Backbone</span><b>{m.backbone}</b></li>
                <li><span>Parameters</span><b>{m.parameters.toLocaleString()}</b></li>
                <li><span>Input channels</span><b>{m.in_channels}</b></li>
                <li><span>Window</span><b>{m.window} frames</b></li>
                <li><span>Trained on</span><b>{m.trained_on}</b></li>
                <li><span>Causal</span><b>{m.causal ? "yes" : "no"}</b></li>
              </ul>
            ) : <p className="card-sub">Available once the API responds.</p>}
          </div>
        </div>
        {gen && !gen.current && (
          <p className="notice warn" role="note" style={{ marginTop: 18 }}>
            <b>Earlier-generation checkpoint.</b> This deployed model {gen.reasons.join(" and ")}.
            The project&apos;s current models are evaluated on the Results and Generalisation
            pages; this demo does not reflect them.
          </p>
        )}
      </TabPanel>

      <TabPanel view="status" id="model-card" value={sub}>
        <Section title="Model card" sub="Generated by the API from the loaded checkpoint, not written by hand.">
          {card ? (
            <div className="cols-2">
              <div className="card">
                <div className="card-title">Intended use</div>
                <p className="card-sub">{card.intended_use}</p>
                <div className="card-title" style={{ marginTop: 14 }}>Out of scope</div>
                <ul className="card-sub" style={{ paddingLeft: 18 }}>{card.out_of_scope.map((x) => <li key={x}>{x}</li>)}</ul>
              </div>
              <div className="card">
                <div className="card-title">Known limits</div>
                <ul className="card-sub" style={{ paddingLeft: 18 }}>{card.limits.map((x) => <li key={x}>{x}</li>)}</ul>
                <p className="card-sub">{card.evaluation}</p>
              </div>
            </div>
          ) : (
            <div className="card">
              <div className="empty">
                {health
                  ? "The deployed backend predates the model card. It appears here once the updated backend is deployed."
                  : "Available once the API responds."}
              </div>
            </div>
          )}
        </Section>
      </TabPanel>

      <TabPanel view="status" id="api" value={sub}>
        <ApiPane health={health} />
      </TabPanel>
    </>
  );
}
